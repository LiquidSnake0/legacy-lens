using System.Text;

namespace LegacyLens.Analysis;

/// <summary>
/// The binary assessment as a document, in the shape and the voice of the
/// source one: what was found, what modern .NET no longer has, what the code
/// uses of the packages going away, and what reading metadata cannot say.
/// </summary>
public class BinaryReportWriter
{
    public DateTimeOffset GeneratedAt { get; init; } = DateTimeOffset.UtcNow;

    public string Write(BinaryAssessment assessment)
    {
        var report = new StringBuilder();

        report.AppendLine($"# {assessment.Name}");
        report.AppendLine();
        report.AppendLine($"A binary assessment, generated on {GeneratedAt:yyyy-MM-dd} by Legacy Lens.");
        report.AppendLine();
        report.AppendLine(
            "Read from the assemblies' metadata with ILSpy's engine. No source was needed, nothing was\n"
          + "decompiled and nothing was run. What metadata cannot tell is listed at the end.");
        report.AppendLine();

        Glance(report, assessment);
        Yours(report, assessment);
        Gaps(report, assessment);
        Used(report, assessment);
        Shipped(report, assessment);
        Unsaid(report, assessment);

        report.AppendLine("---");
        report.AppendLine();
        report.AppendLine($"Read in {assessment.ElapsedMs:N0} ms. Generated by [Legacy Lens](https://github.com/LiquidSnake0/legacy-lens).");
        report.AppendLine();
        return report.ToString();
    }

    private static void Glance(StringBuilder report, BinaryAssessment assessment)
    {
        var frameworks = assessment.Yours
            .GroupBy(a => Short(a.Framework))
            .OrderByDescending(g => g.Count())
            .Select(g => $"{g.Key} ({g.Count()})");

        report.AppendLine("## At a glance");
        report.AppendLine();
        report.AppendLine("| | |");
        report.AppendLine("|---|---|");
        report.AppendLine($"| Your assemblies | {assessment.Yours.Count:N0} |");
        report.AppendLine($"| Third-party assemblies shipped with them | {assessment.ThirdParty.Count:N0} |");
        report.AppendLine($"| Files that are not .NET assemblies | {assessment.NotManaged.Count:N0} |");
        if (assessment.Yours.Count > 0)
            report.AppendLine($"| Your assemblies target | {string.Join(", ", frameworks)} |");
        report.AppendLine($"| Parts of the .NET Framework modern .NET does not have | {assessment.Gaps.Count:N0} |");
        report.AppendLine($"| Packages going away that your code uses | {assessment.Uses.Count:N0} |");
        report.AppendLine();
    }

    private static void Yours(StringBuilder report, BinaryAssessment assessment)
    {
        if (assessment.Yours.Count == 0) return;

        var names = assessment.Yours.Select(a => a.Name).ToHashSet(StringComparer.Ordinal);

        report.AppendLine("## Your assemblies");
        report.AppendLine();
        report.AppendLine("| Assembly | Version | Target | Types | Depends on your |");
        report.AppendLine("|---|---|---|---:|---|");
        foreach (var assembly in assessment.Yours)
        {
            var own = assembly.References.Where(names.Contains).ToList();
            report.AppendLine(
                $"| `{assembly.Name}`{(assembly.Executable ? " (exe)" : "")} | {assembly.Version} | {Short(assembly.Framework)} | "
              + $"{assembly.Types:N0} | {(own.Count == 0 ? "nothing" : string.Join(", ", own.Select(n => $"`{n}`")))} |");
        }
        report.AppendLine();
    }

    private static void Gaps(StringBuilder report, BinaryAssessment assessment)
    {
        if (assessment.Gaps.Count == 0) return;

        report.AppendLine("## What modern .NET no longer has");
        report.AppendLine();
        report.AppendLine("| Framework assembly | Members used | Used by | Why it matters |");
        report.AppendLine("|---|---:|---|---|");
        foreach (var gap in assessment.Gaps)
        {
            report.AppendLine(
                $"| `{gap.Assembly}` | {gap.Members:N0} | {string.Join(", ", gap.UsedBy.Select(n => $"`{n}`"))} | {gap.Why} |");
        }
        report.AppendLine();
    }

    private static void Used(StringBuilder report, BinaryAssessment assessment)
    {
        if (assessment.Uses.Count == 0) return;

        report.AppendLine("## What you actually use of what is going away");
        report.AppendLine();
        report.AppendLine(
            "Each type is attributed to the assembly the compiler resolved it to, so nothing here is\n"
          + "guessed from a namespace. A count is of distinct members referenced, not of calls.");
        report.AppendLine();
        report.AppendLine("| Package | Members used | Types | Your assemblies | Replaced by | Covered |");
        report.AppendLine("|---|---:|---:|---:|---|---:|");
        foreach (var dependency in assessment.Uses)
        {
            var surface = dependency.Surface;
            var best = dependency.Best is { Candidate.Length: > 0 } named ? named : null;
            report.AppendLine(
                $"| `{surface.Package}` | {surface.Uses:N0} | {surface.Types.Count:N0} | {surface.Files:N0} | "
              + $"{(best is null ? "nothing recorded" : $"`{best.Candidate}`")} | {(best is null ? "" : $"{best.Percent}%")} |");
        }
        report.AppendLine();

        foreach (var dependency in assessment.Uses)
        {
            var surface = dependency.Surface;
            var best = dependency.Best is { Candidate.Length: > 0 } named ? named : null;
            var fates = new Dictionary<string, string>(StringComparer.Ordinal);
            if (best is not null)
            {
                foreach (var type in best.Covered) fates[type.Name] = $"replaced in {best.Candidate}";
                foreach (var type in best.Unknown) fates[type.Name] = "unknown to the catalogue";
                foreach (var type in best.Gone) fates[type.Name] = "**deleted**: the feature was withdrawn";
                foreach (var type in best.Unavailable) fates[type.Name] = "**no replacement recorded**";
            }

            report.AppendLine($"### {surface.Package}");
            report.AppendLine();
            report.AppendLine("| Type | Members used | In assemblies | What happens to it |");
            report.AppendLine("|---|---:|---:|---|");
            foreach (var type in surface.Types)
                report.AppendLine($"| `{type.Name}` | {type.Uses:N0} | {type.Files:N0} | {fates.GetValueOrDefault(type.Name, "nothing recorded")} |");
            report.AppendLine();
        }
    }

    private static void Shipped(StringBuilder report, BinaryAssessment assessment)
    {
        if (assessment.ThirdParty.Count == 0) return;

        report.AppendLine("## Shipped alongside");
        report.AppendLine();
        report.AppendLine(string.Join(", ",
            assessment.ThirdParty.Select(a => $"`{a.Name}` {a.Version} ({Short(a.Framework)})")) + ".");
        report.AppendLine();
    }

    private static void Unsaid(StringBuilder report, BinaryAssessment assessment)
    {
        report.AppendLine("## What this report does not say");
        report.AppendLine();
        report.AppendLine(assessment.Prefixes is { Count: > 0 } prefixes
            ? $"**Which assemblies are yours was given, not measured.** Those whose name starts with "
            + string.Join(" or ", prefixes.Select(p => $"`{p}`")) + "; everything else is listed as shipped alongside."
            : "**Which assemblies are yours is a rule, not a measurement.** An assembly is counted as\n"
            + "yours when it has no strong name and is not a package this tool knows. An application's own\n"
            + "assemblies are rarely signed and Microsoft's always are; a signed assembly of your own is\n"
            + "listed as shipped alongside, and an unsigned tool shipped in the same folder is counted as\n"
            + "yours. `--yours <prefix>` says which are.");
        report.AppendLine();
        report.AppendLine(
            "**Members, not calls.** Metadata records each member a type references once, however often\n"
          + "the code calls it. A method called a thousand times counts one.");
        report.AppendLine();
        report.AppendLine(
            "**No complexity, no history, no tests.** Those are read from source and from git, and\n"
          + "neither is here. The ranking of risky files needs them and is not attempted.");
        report.AppendLine();
        if (assessment.NotManaged.Count > 0)
        {
            report.AppendLine(
                $"**{assessment.NotManaged.Count:N0} files are not .NET assemblies** (native libraries, or files\n"
              + "that could not be read) and were left out.");
            report.AppendLine();
        }
    }

    /// <summary>".NETFramework,Version=v4.8" read as ".NET Framework 4.8".</summary>
    private static string Short(string framework)
    {
        if (string.IsNullOrEmpty(framework)) return "not stated";
        var parts = framework.Split(",Version=v");
        return parts.Length == 2
            ? parts[0] switch
            {
                ".NETFramework" => $".NET Framework {parts[1]}",
                ".NETCoreApp" => $".NET {parts[1]}",
                ".NETStandard" => $".NET Standard {parts[1]}",
                _ => framework,
            }
            : framework;
    }
}
